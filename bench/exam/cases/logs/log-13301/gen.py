#!/usr/bin/env python3
"""Generates log-13301 (gateway.log, request chain). Fixed seed; run from anywhere."""
import random, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "gen"))
from _lib import write_case, offsets, check_size, PREFIX

CANARY = "EXAM-CANARY-3a91c7e2"
rng = random.Random(13301)
SVCS = ["gateway", "auth-svc", "order-svc", "stock-svc", "billing-svc", "notify-svc", "search-svc", "cart-svc", "profile-svc"]
MSGS = ["GET /api/v2/items 200 %dms", "POST /api/v2/cart 201 %dms", "token refreshed in %dms", "cache hit ratio 0.%02d",
        "query ok rows=%d", "GET /api/v2/profile 200 %dms", "health probe ok %dms", "queue depth %d"]
TARGET, DECOY = "req-7f3a2c", "req-7f3a2d"
CHAIN = ["gateway", "auth-svc", "order-svc", "stock-svc", "billing-svc", "notify-svc"]
DECOY_CHAIN = ["gateway", "auth-svc", "search-svc", "cart-svc"]


def rid():
    return "req-%06x" % rng.randrange(0x1000000)


def line(t, svc, lvl, req, msg):
    return "%s [%s] %s req=%s %s" % (t, svc, lvl, req, msg)


def ts(sec):
    return "2026-09-15T%02d:%02d:%02d.%03dZ" % (sec // 3600, sec // 60 % 60, sec % 60, rng.randrange(1000))


N = 1500
lines = ["# gateway.log format=v2 host=gw-edge-02 date=2026-09-15"]
sec = 6 * 3600
plan = {}
for k, svc in enumerate(CHAIN):
    plan[int(N * 0.66) + k * 37] = (TARGET, svc)
for k, svc in enumerate(DECOY_CHAIN):
    plan[int(N * 0.40) + k * 29] = (DECOY, svc)      # decoy chain, partly before 64KB
    plan[int(N * 0.70) + k * 41 + 3] = (DECOY, svc)
for i in range(N):
    sec += rng.randrange(1, 4)
    if i in plan:
        r, svc = plan[i]
        msg = "forward -> %s" % svc if svc != "gateway" else "accepted POST /api/v2/checkout"
        lines.append(line(ts(sec), svc, "INFO", r, msg))
        continue
    svc = SVCS[rng.randrange(len(SVCS))]
    m = MSGS[rng.randrange(len(MSGS))]
    m = m % rng.randrange(3, 400) if "%" in m else m
    lvl = "WARN" if rng.random() < 0.04 else "INFO"
    lines.append(line(ts(sec), svc, lvl, rid(), m))
text = "\n".join(lines) + "\n"
size = check_size(text, 80_000, 200_000)
assert TARGET + " " not in text[:PREFIX] and min(offsets(text, "req=" + TARGET + " ")) >= PREFIX
assert "req=" + TARGET + "\n" not in text

case = {
    "id": "log-13301",
    "description": "Trace one request id through a 100KB+ gateway log and list the services in order. " + CANARY,
    "category": "logs",
    "tags": {"scenario": "logs", "task_type": "locate_error", "traps": ["TR-LONG", "TR-DECOY"],
             "trap_decoys": {"TR-LONG": "gateway → auth-svc → search-svc → cart-svc", "TR-DECOY": "gateway → auth-svc → search-svc → cart-svc"},
             "axes": ["LNG", "OBS"], "level": "L2", "family": "fam-logs-longtrace-01", "answer_style": "natural",
             "ref_calls": 2, "fixture_bytes": size, "status": "draft", "version": 1,
             "author": "llm:claude-sonnet-5-5", "reviewer": None},
    "files": {"gateway.log": text},
    "turns": [{"prompt": "我把网关日志（gateway.log）丢进来了，帮我看看 req-7f3a2c 这个请求都经过了哪几个服务，按先后顺序告诉我。",
               "expect": {"output_contains_any": [sep.join(CHAIN) for sep in ["→", " → ", "->", " -> ", " > ", "、", ", ", "，", " ", "/"]],
                          "output_excludes": ["search-svc"]}}],
}
VERIFY = '''# %s : exam gap-fill case
import json, re
case = json.load(open("case.json", encoding="utf-8"))
log = case["files"]["gateway.log"]
assert log.startswith("# gateway.log format=v2")
chain = []
for ln in log.splitlines():
    m = re.search(r"\\[([a-z-]+)\\] \\w+ req=req-7f3a2c ", ln)
    if m and m.group(1) not in chain:
        chain.append(m.group(1))
seps = ["→", " → ", "->", " -> ", " > ", "、", ", ", "，", " ", "/"]
print(json.dumps({"expected_contains_any": [s.join(chain) for s in seps]}, ensure_ascii=False))
''' % CANARY
NOTES = '''## Traps
- TR-LONG: gateway.log is %d bytes; the 6 lines of req-7f3a2c all sit after byte 65536 (first at %d). Reading only the first page finds no trace of it.
- TR-DECOY: req-7f3a2d (one hex digit apart) has a different chain (gateway → auth-svc → search-svc → cart-svc) whose lines start before 64KB; grepping a prefix of the id returns both.
## Reference solution
1. search_text / grep `req=req-7f3a2c ` in gateway.log (2 calls at most: search, then optional read_lines to confirm order).
## Why the answer is unique
Each service appears exactly once for the target id, file order equals time order; chain gateway → auth-svc → order-svc → stock-svc → billing-svc → notify-svc. The decoy chain contains search-svc/cart-svc, which never appear for the target (output_excludes search-svc).

Generated by gen.py (seed 13301); regenerate with `python3 gen.py`.

%s
''' % (size, min(offsets(text, "req=" + TARGET + " ")), CANARY)
write_case(HERE, case, VERIFY, NOTES)
print("ok", size)
