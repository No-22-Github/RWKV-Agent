"""Shared helpers for the g4 (long input) gap-fill cases. gen.py of each case imports this."""
import json
import os
import random
import sys
from pathlib import Path

G4 = Path(__file__).resolve().parent
PREFIX = 64 * 1024


def write_case(case_dir, case, verify_py, notes):
    """Write case.json (true fixture_bytes), verify.py and NOTES.md next to gen.py."""
    case_dir = Path(case_dir)
    case["tags"]["fixture_bytes"] = sum(len(v.encode("utf-8")) for v in case["files"].values())
    (case_dir / "case.json").write_text(json.dumps(case, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (case_dir / "verify.py").write_text(verify_py, encoding="utf-8")
    (case_dir / "NOTES.md").write_text(notes, encoding="utf-8")


def offsets(text, needle):
    """Byte offsets of every line containing needle."""
    out, pos = [], 0
    for line in text.split("\n"):
        if needle in line:
            out.append(pos)
        pos += len(line.encode("utf-8")) + 1
    return out


def check_size(text, lo, hi):
    n = len(text.encode("utf-8"))
    assert lo <= n <= hi, f"size {n} outside [{lo},{hi}]"
    return n


def pick(rng, seq):
    return seq[rng.randrange(len(seq))]


def finish(here, cid, canary, scenario, task_type, traps, decoys, level, files, prompt, expect, desc,
           verify_body, notes_body, axes=None, ref_calls=2):
    """Assemble case.json + verify.py + NOTES.md. verify_body is python code run after
    `case = json.load(...)` and must print the JSON answer; it can assume `import json, re, csv, io`."""
    axes = axes or ["LNG", "OBS"]
    case = {
        "id": cid, "description": desc + " " + canary, "category": scenario,
        "tags": {"scenario": scenario, "task_type": task_type, "traps": traps, "trap_decoys": decoys,
                 "axes": axes, "level": level, "family": "fam-g4-" + cid, "answer_style": "natural",
                 "ref_calls": ref_calls, "fixture_bytes": 0, "status": "draft", "version": 1,
                 "author": "llm:claude-sonnet-5-5", "reviewer": None},
        "files": files,
        "turns": [{"prompt": prompt, "expect": expect}],
    }
    verify = "# %s : exam gap-fill case\nimport json, re, csv, io\ncase = json.load(open(\"case.json\", encoding=\"utf-8\"))\n%s\n" % (canary, verify_body)
    notes = notes_body.rstrip() + "\n\nGenerated by gen.py with a fixed seed; regenerate with `python3 gen.py`.\n\n" + canary + "\n"
    write_case(here, case, verify, notes)
    return case


def build_log(rng, header, n, start_sec, svcs, msgs, specials, date="2026-09-15", step=(1, 4), warn=0.04, err=0.0,
              err_msgs=None):
    """Return log text. specials: {line_index: (svc, level, req, msg, sec_override|None)}; indexes are noise-line slots.
    Lines look like: 2026-09-15T06:00:01.123Z [svc] LEVEL req=req-xxxxxx msg"""
    lines = [header]
    sec = start_sec
    for i in range(n):
        sec += rng.randrange(*step)
        if i in specials:
            svc, lvl, req, msg = specials[i][:4]
            if len(specials[i]) > 4 and specials[i][4] is not None:
                sec = specials[i][4]
        else:
            svc = pick(rng, svcs)
            m = pick(rng, msgs)
            msg = m % rng.randrange(3, 400) if "%" in m else m
            req = "req-%06x" % rng.randrange(0x1000000)
            r = rng.random()
            lvl = "ERROR" if r < err else ("WARN" if r < err + warn else "INFO")
            if lvl == "ERROR" and err_msgs:
                msg = pick(rng, err_msgs)
        lines.append("%sT%02d:%02d:%02d.%03dZ [%s] %s req=%s %s" % (
            date, sec // 3600, sec // 60 % 60, sec % 60, rng.randrange(1000), svc, lvl, req, msg))
    return "\n".join(lines) + "\n"


def prefix_lines(text):
    """Number of complete lines within the first 64KB (byte-accurate, safe for CJK)."""
    return text.encode("utf-8")[:PREFIX].count(b"\n")
