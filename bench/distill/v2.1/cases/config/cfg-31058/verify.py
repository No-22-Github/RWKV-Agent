assert _pin == '71b5ad13664407fc4a98d71591d3d0fbe5429d697762824b21f1900d54edd9ae', "fixture changed"

def apply(files, ops):
    out = dict(files)
    for op in ops:
        if op[0] == "sub":
            _, path, old, new = op
            assert out[path].count(old) == 1, (path, old)
            out[path] = out[path].replace(old, new)
        elif op[0] == "app":
            out[op[1]] = out[op[1]] + op[2]
    return out

OPS = json.loads('[["sub", "manifest.json", "  \\"author\\": \\"Mara Ito\\"\\n", "  \\"author\\": \\"Mara Ito\\",\\n  \\"license\\": \\"MIT\\"\\n"]]')
end = apply(case["files"], OPS)
print(json.dumps({"files": {p: t for p, t in end.items() if case["files"][p] != t}}, ensure_ascii=False))
