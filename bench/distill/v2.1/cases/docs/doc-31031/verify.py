assert _pin == '9874286e59b7c7051bdd7afe2e466cdd51b31b56f296a405642ce348be51039a', "fixture changed"

def apply(files, ops):
    out = dict(files)
    for op in ops:
        if op[0] == "sub":
            _, path, old, new = op
            assert out[path].count(old) == 1, (path, old)
            out[path] = out[path].replace(old, new)
        elif op[0] == "app":
            out[op[1]] = out[op[1]] + op[2]
    return out

OPS = json.loads('[["app", "release/notes-2026.txt", "\\n== 2026-09 ==\\nship: export center\\nfix: timezone drift\\n"]]')
end = apply(case["files"], OPS)
