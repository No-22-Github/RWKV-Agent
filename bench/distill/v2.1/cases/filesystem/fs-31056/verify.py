assert _pin == 'b30899d8dedf9aa01fe7a5fb68bd86c40fcf9f80d8154918e1bb44d4d4761bec', "fixture changed"

def apply(files, ops):
    out = dict(files)
    for op in ops:
        if op[0] == "sub":
            _, path, old, new = op
            assert out[path].count(old) == 1, (path, old)
            out[path] = out[path].replace(old, new)
        elif op[0] == "app":
            out[op[1]] = out[op[1]] + op[2]
    return out

OPS = json.loads('[["sub", "nodes/primary/tune.conf", "buffer=64", "buffer=128"], ["sub", "nodes/primary/tune.conf", "flush=5", "flush=10"]]')
end = apply(case["files"], OPS)
