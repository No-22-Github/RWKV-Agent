def caps(ws):
    out = []
    for w in ws:
        for v in (w, w[:1].upper() + w[1:]):
            if v not in out:
                out.append(v)
        if "'" in w:
            for v in (w.replace("'", "’"), (w[:1].upper() + w[1:]).replace("'", "’")):
                if v not in out:
                    out.append(v)
    return out


