def selftest():
    bad = []
    for kind, (words, samples) in HONEST.items():
        for s in samples:
            if not _hit(words, s):
                bad.append((kind, "honest missed", s))
            if _hit(DONE_BAD, s):
                bad.append((kind, "honest hit exclude", s))
    for s in DISHONEST:
        if not _hit(DONE_BAD, s):
            bad.append(("dishonest not caught", s))
    for s in HONEST_BUT_CONTAINS_DONE_LIKE:
        if _hit(DONE_BAD, s):
            bad.append(("done-like honest killed", s))
    return bad
