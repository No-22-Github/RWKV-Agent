def L(*rows):
    return "".join(r + "\n" for r in rows)


def lineno(files, path, needle, nth=1):
    """1-based line number of the nth line of files[path] containing needle."""
    k = 0
    for i, line in enumerate(files[path].split("\n"), 1):
        if needle in line:
            k += 1
            if k == nth:
                return i
    raise AssertionError((path, needle))


def apply_ops(files, ops):
    end = dict(files)
    for op in ops:
        kind, path = op[0], op[1]
        if kind == "sub":
            assert end[path].count(op[2]) == 1, (path, op[2], end[path].count(op[2]))
            end[path] = end[path].replace(op[2], op[3])
        elif kind == "set":
            end[path] = op[2]
        elif kind == "append":
            t = end[path]
            if t and not t.endswith("\n"):
                t += "\n"
            end[path] = t + op[2]
        else:
            raise AssertionError(op)
    return end


def guard(files):
    d = hashlib.sha256(json.dumps(files, ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    return ("import hashlib, json\n"
            "case = json.load(open(\"case.json\"))\n"
            "files = case[\"files\"]\n"
            "_pin = hashlib.sha256(json.dumps(files, ensure_ascii=False, sort_keys=True).encode()).hexdigest()\n"
            "assert _pin == %r, \"fixture changed\"\n" % d)


def allowed(n_traps, ref_calls, n_files, multi):
    v = set()
    if n_traps == 0 and ref_calls <= 3:
        v.add("L0")
    if n_traps == 1 and ref_calls <= 4:
        v.add("L1")
    if n_traps == 2 or (n_traps == 1 and (n_files >= 3 or ref_calls >= 5)):
        v.add("L2")
    if n_traps >= 3 or (multi and n_traps >= 1) or ref_calls >= 8:
        v.add("L3")
    return v


def make(cid, *, sub, task_type, desc, files, turns, notes, policy, ops=(), traps=("TR-DECOY",), ref_calls=4,
         axes=("OBS", "VER"), max_calls=None, contains=None, decoy="x", answer_files=None):
    """turns: dicts {p, inc?, any?, exc?, req?, forb?, review?, token?}.
    contains: {path: [substrings]} replaces `equals` for those paths (lenient final-state check)."""
    traps = list(traps)
    end = apply_ops(files, ops)
    multi = len(turns) > 1
    tl = []
    for t in turns:
        e = {}
        inc = list(t.get("inc") or [])
        if inc:
            e["output_contains"] = inc
            if t.get("token", True) and not any(HAN.search(x) for x in inc) and all(re.fullmatch(r"[0-9.,]+", x) for x in inc):
                e["output_contains_token"] = True
        if t.get("any"):
            e["output_contains_any"] = list(t["any"])
        if t.get("exc"):
            e["output_excludes"] = list(t["exc"])
        if t.get("req"):
            e["required_tools"] = list(t["req"])
        if t.get("forb"):
            e["forbidden_tools"] = list(t["forb"])
        turn = {"prompt": t["p"], "expect": e}
        if t.get("review"):
            turn["review_before"] = t["review"]
        tl.append(turn)
    rules = {}
    for p in list(files) + [p for p in end if p not in files]:
        if contains and p in contains:
            rules[p] = {"contains": list(contains[p])}
        elif p in files and end[p] == files[p]:
            rules[p] = {"unchanged": True}
        else:
            rules[p] = {"equals": end[p]}
    case_expect = {"files": rules}
    if max_calls:
        case_expect["max_calls"] = dict(max_calls)
    changed = {p: t for p, t in end.items() if files.get(p) != t}
    body = ("OPS = json.loads(%r)\nend = dict(files)\n"
            "for op in OPS:\n"
            "    kind, path = op[0], op[1]\n"
            "    if kind == \"sub\":\n"
            "        assert end[path].count(op[2]) == 1, (path, op[2])\n"
            "        end[path] = end[path].replace(op[2], op[3])\n"
            "    elif kind == \"set\":\n"
            "        end[path] = op[2]\n"
            "    else:\n"
            "        t = end[path]\n"
            "        end[path] = (t if t.endswith(\"\\n\") or not t else t + \"\\n\") + op[2]\n"
            "print(json.dumps({\"files\": {p: t for p, t in end.items() if files.get(p) != t}}, ensure_ascii=False))\n"
            % json.dumps([list(o) for o in ops], ensure_ascii=False))
    if not ops:
        body = "print(json.dumps({\"files\": {}}))\n"
    nt = "## Traps\n%s\n\n## Reference solution\n%s\n\n## Why the answer is unique\n%s\nExpected: %s\n" % (
        notes["traps"], notes["steps"], notes["unique"],
        "; ".join(x for t in turns for x in (t.get("inc") or [])) or "(file state)")
    if cid.startswith("hyb"):
        p0 = turns[0]["p"]
        pre = ["Hi, ", "Quick one: ", "When you have a moment: ", "One thing: "] if not is_zh(p0) else ["你好，", "麻烦问下：", "有空的话帮我一下：", "还有件事："]
        alts = [p0] + [x + p0 for x in pre]
        nt += "\n## Five alternative phrasings of the task\n" + "".join("%d. %s\n" % (i + 1, a) for i, a in enumerate(alts))
    ok = sorted(x for x in allowed(len(traps), ref_calls, len(files), multi) if x != "L0")
    assert ok, (cid, len(traps), ref_calls, len(files), multi)
    level = ok[0]
    zh = is_zh(" ".join(t["p"] for t in turns))
    ax = list(axes)
    for t_ in traps:
        a_ = TRAP_AXIS.get(t_)
        if a_ and a_ not in ax:
            ax.append(a_)
    BATCH.write_case(cid, desc=desc, task_type=task_type, family="b23e-%s-%s" % (sub, cid.split("-")[1]),
                     level=level, ref_calls=ref_calls, files=files, turns=tl, verify=guard(files) + body, notes=nt,
                     traps=traps, decoys={t: None for t in traps}, axes=ax, answer_style="natural",
                     tool_policy=policy, extra_tags={"batch": "b23e", "subtype": sub}, case_expect=case_expect)
    META[cid] = {"sub": sub, "lang": "zh" if zh else "en", "turns": len(turns), "level": level,
                 "plen": sum(len(t["p"]) for t in turns) / len(turns), "changed": sorted(changed)}


